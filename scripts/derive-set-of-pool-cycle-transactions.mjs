#!/usr/bin/env node
/**
 * Books one closed cycle's directed-yield split. The cycle's Beancount directives are first kept
 * in the one log, as the `cycle-transactions` pool receipt in the semantic record journal; the
 * dated sidecar in this package's ledger records (books are records) is then rendered whole from every
 * booking the journal holds for that sidecar, headed like the Group's other generated sidecars --
 * never the main ledger itself. The sidecar is a projection: deleting it loses nothing. Reads the
 * persisted `derive-cycle-split.mjs` result off the pool's store and derives its transaction set
 * (`deriveSetOfPoolCycleTransactions`).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { parseArgs } from "node:util";
import { deriveSetOfPoolCycleTransactions } from "../src/cycle-transactions.mjs";
import { dataKindDirectory } from "@red-cup-engineering/eavt-services-section/data-artifact-address";
import { packageRoot, readStore, writeStore } from "../src/store.mjs";
import { recordNiForBytes } from "../src/ledger-witness.mjs";
import { poolReceipts, recordPoolReceipt } from "../src/receipts.mjs";

const HEADER = "; Generated by scripts/derive-set-of-pool-cycle-transactions.mjs (@red-cup-engineering/pool-service). Do not hand-edit.\n";
const OPEN_LINE = /^\d{4}-\d{2}-\d{2} open (\S+)$/mu;

function existingOpenAccounts(text) {
  const accounts = new Set();
  for (const line of text.split("\n")) {
    const match = OPEN_LINE.exec(line);
    if (match) accounts.add(match[1]);
  }
  return [...accounts];
}

/** The sidecar's own content below its header, as one block. */
function sidecarBody(text) {
  return (text.startsWith(HEADER) ? text.slice(HEADER.length) : text).replace(/^\n+/u, "").trimEnd();
}

/** The bookings the journal holds for one sidecar, in the order recorded. */
function sidecarBookings(journalRoot, sidecarPath) {
  return poolReceipts(journalRoot, "cycle-transactions").filter(({ record }) => record?.sidecarPath === sidecarPath && Array.isArray(record.blocks));
}

/** The sidecar as a projection of the journal: the header, then every held booking's blocks. */
export function renderPoolCycleSidecar(journalRoot, sidecarPath) {
  const blocks = sidecarBookings(journalRoot, sidecarPath).flatMap(({ record }) => record.blocks);
  return `${[HEADER, ...blocks].join("\n\n")}\n`;
}

/**
 * Derives and books `request.cycleId`'s transaction set against the pool document at
 * `statePath`, keeping it in the journal and rendering the dated sidecar from the journal.
 * A sidecar written before bookings were kept in the journal is admitted into it once, as it is,
 * so the projection keeps every booking it already carried.
 * @param {string} statePath Path to the pool's persisted JSON document.
 * @param {string} journalRoot Settlement root the receipts are kept under.
 * @param {object} request `{cycleId, directedYieldReceipts, drawFees?, receivedAt, distributedAt, recordedAt}`.
 * @param {{sidecarPath?: string, knownOpenPaths?: string[]}} [options] `sidecarPath` overrides the default dated path; `knownOpenPaths` names other Beancount files (e.g. the main ledger) already carrying an account, so this sidecar never re-`open`s it.
 * @returns {{booked: true, recovered: boolean, path: string, sidecarNi: string, transactionCount: number, receipt: string}|{booked: false, reason: string}} What was booked (recovered when the journal or an earlier sidecar already held it), or a refusal naming why.
 * @throws {Error} When no cycle-split document exists at `statePath` for `request.cycleId`.
 */
export function deriveSetOfPoolCycleTransactionsFromStore(statePath, journalRoot, request, options = {}) {
  const document = readStore(statePath, null);
  const split = document?.cycleSplits?.find((s) => s.cycleId === request.cycleId);
  if (!split) throw new Error(`derive-set-of-pool-cycle-transactions: no cycle-split document for cycle "${request.cycleId}" at ${statePath}`);

  const existingBooking = (document.cycleBookings ?? []).find((booking) => booking.cycleId === request.cycleId);
  if (existingBooking) {
    return { booked: false, reason: `cycle "${request.cycleId}" is already booked (booking receipt ${existingBooking.receipt})` };
  }

  const date = request.receivedAt.slice(0, 10);
  const sidecarPath = options.sidecarPath ?? join(dataKindDirectory(packageRoot(), "record", "ledger"), `${date}-pool-cycle-transactions.beancount`);
  const priorText = existsSync(sidecarPath) ? readFileSync(sidecarPath, "utf8") : "";

  // A sidecar from before the journal kept bookings: admit what it carries once, as it is.
  if (sidecarBookings(journalRoot, sidecarPath).length === 0 && sidecarBody(priorText) !== "") {
    recordPoolReceipt(journalRoot, "cycle-transactions", { sidecarPath, admitted: "pre-journal-sidecar", blocks: [sidecarBody(priorText)] }, request.recordedAt);
  }

  const persistBooking = (receiptId, transactionCount, commodity, recovered) => {
    const sidecarText = renderPoolCycleSidecar(journalRoot, sidecarPath);
    mkdirSync(dirname(sidecarPath), { recursive: true });
    writeFileSync(sidecarPath, sidecarText);
    const sidecarNi = recordNiForBytes(sidecarText);
    const booking = Object.freeze({ cycleId: request.cycleId, commodity, transactionCount, sidecarPath, sidecarNi, receipt: receiptId, recordedAt: request.recordedAt, recovered });
    writeStore(statePath, { ...document, cycleBookings: [...(document.cycleBookings ?? []), booking] });
    return { booked: true, recovered, path: sidecarPath, sidecarNi, transactionCount, receipt: receiptId };
  };

  // The journal already holds this cycle's booking (the state write was lost): finish it.
  const held = sidecarBookings(journalRoot, sidecarPath).find(({ record }) => record.cycleId === request.cycleId);
  if (held) return persistBooking(held.id, held.record.transactionCount, held.record.commodity, true);

  const currentText = renderPoolCycleSidecar(journalRoot, sidecarPath);
  const knownOpenText = (options.knownOpenPaths ?? []).filter(existsSync).map((path) => readFileSync(path, "utf8")).join("\n");
  const openAccounts = [...new Set([...existingOpenAccounts(currentText), ...existingOpenAccounts(knownOpenText)])];

  const result = deriveSetOfPoolCycleTransactions({
    split,
    directedYieldReceipts: request.directedYieldReceipts,
    drawFees: request.drawFees ?? [],
    receivedAt: request.receivedAt,
    distributedAt: request.distributedAt,
    openAccounts,
  });
  if (!result.derived) return { booked: false, reason: result.reason };

  // An earlier sidecar already carries this cycle: recover only when every expected directive is there.
  if (currentText.includes(`cycle_id: "${request.cycleId}"`)) {
    const missing = result.transactions.filter((transaction) => !currentText.includes(transaction.directive));
    if (missing.length > 0) {
      return { booked: false, reason: `cycle "${request.cycleId}" appears in ${sidecarPath}, but ${missing.length} expected transaction directive(s) are missing; refusing recovery` };
    }
    const receipt = recordPoolReceipt(journalRoot, "cycle-transactions", {
      cycleId: result.cycleId, commodity: result.commodity, transactionCount: result.transactionCount, sidecarPath, blocks: [], recovered: true,
    }, request.recordedAt);
    return persistBooking(receipt.id, result.transactionCount, result.commodity, true);
  }

  const receipt = recordPoolReceipt(journalRoot, "cycle-transactions", {
    cycleId: result.cycleId,
    commodity: result.commodity,
    transactionCount: result.transactionCount,
    sidecarPath,
    blocks: [...result.accountsToOpen.map((entry) => entry.directive), ...result.transactions.map((t) => t.directive)],
    recovered: false,
  }, request.recordedAt);
  return persistBooking(receipt.id, result.transactionCount, result.commodity, false);
}

if (import.meta.main) {
  const { values } = parseArgs({
    options: {
      state: { type: "string" },
      "journal-root": { type: "string" },
      request: { type: "string" },
      out: { type: "string" },
      "known-open": { type: "string", multiple: true },
    },
  });
  if (!values.state) {
    process.stderr.write("error: --state is required\n");
    process.exitCode = 2;
  } else {
    const journalRoot = values["journal-root"] ?? dirname(resolve(values.state));
    const requestText = values.request ?? readFileSync(0, "utf8");
    const result = deriveSetOfPoolCycleTransactionsFromStore(values.state, journalRoot, JSON.parse(requestText), { sidecarPath: values.out, knownOpenPaths: values["known-open"] });
    process.stdout.write(`${JSON.stringify(result)}\n`);
    if (!result.booked) process.exitCode = 1;
  }
}

import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Interface } from "ethers";
import { findRegisteredWallet, reconcilePoolReceipts, sumBookedPostings } from "../scripts/reconcile-pool-receipts.mjs";

const WALLET_ADDRESS = "0x32886F6F361C1d570255c2762967A2e41D0E9B1a";
const REGISTRY = { wallets: [{ id: "tidepool-pool-base", chain: "base", address: WALLET_ADDRESS }, { id: "other-hive-wallet", chain: "hive", address: "someone" }] };

const erc20 = new Interface([
  "function balanceOf(address) view returns (uint256)",
  "function decimals() view returns (uint8)",
  "function symbol() view returns (string)",
]);

function rpcFake(byFunction) {
  return async (url, init) => {
    const body = JSON.parse(init.body);
    const [{ data }] = body.params;
    for (const [fn, result] of Object.entries(byFunction)) {
      if (data.startsWith(erc20.getFunction(fn).selector)) {
        return { ok: true, status: 200, json: async () => ({ jsonrpc: "2.0", id: 1, result: erc20.encodeFunctionResult(fn, [result]) }) };
      }
    }
    return { ok: false, status: 500, json: async () => ({}) };
  };
}

test("findRegisteredWallet: finds a wallet by id, or returns null", () => {
  assert.deepEqual(findRegisteredWallet(REGISTRY, "tidepool-pool-base"), { address: WALLET_ADDRESS, chain: "base" });
  assert.equal(findRegisteredWallet(REGISTRY, "tidepool-pool-base-DOES-NOT-EXIST"), null);
});

test("sumBookedPostings: sums signed postings to the named accounts across a sidecar's text", () => {
  const text = [
    "; Generated by scripts/derive-set-of-pool-cycle-transactions.mjs. Do not hand-edit.",
    "",
    '2026-09-01 * "Tidepool cycle 2026-09-cycle-1 directed yield received"',
    "  Assets:Digital-Assets:EVM:Base:Pool:Barrier-Reserve  20 USDC",
    "  Assets:Digital-Assets:EVM:Base:Pool:Float  30 USDC",
    "  Assets:Digital-Assets:EVM:Base:Pool:Distributable-Pending  50 USDC",
    "  Income:Pool:Directed-Yield  -100 USDC",
    "",
    '2026-09-05 * "Tidepool cycle 2026-09-cycle-1 distribution to ent-1"',
    "  Assets:Digital-Assets:EVM:Base:Pool:Distributable-Pending  -25 USDC",
    "  Expenses:Pool:Enterprise-Distributions:Ent-1  25 USDC",
    "",
  ].join("\n");
  const result = sumBookedPostings(text, [
    "Assets:Digital-Assets:EVM:Base:Pool:Barrier-Reserve",
    "Assets:Digital-Assets:EVM:Base:Pool:Float",
    "Assets:Digital-Assets:EVM:Base:Pool:Distributable-Pending",
  ]);
  assert.equal(result.amount, "75"); // 20 + 30 + 50 - 25
  assert.equal(result.commodity, "USDC");
});

test("reconcilePoolReceipts: refuses, naming the missing registry row, when the pool's Base wallet is not registered", async () => {
  const dir = mkdtempSync(join(tmpdir(), "pool-service-reconcile-receipts-"));
  const registryPath = join(dir, "wallet-registry.json");
  writeFileSync(registryPath, JSON.stringify({ wallets: [] }));
  const sidecarPath = join(dir, "sidecar.beancount");
  writeFileSync(sidecarPath, "");

  const result = await reconcilePoolReceipts({ walletRegistryPath: registryPath, walletId: "tidepool-pool-base", sidecarPath, journalRoot: dir, recordedAt: "2026-09-05T00:00:00Z" });
  assert.equal(result.reconciled, false);
  assert.match(result.reason, /no wallet registered under id "tidepool-pool-base"/);
});

test("reconcilePoolReceipts: agrees when the live balance matches the booked running balance", async () => {
  const dir = mkdtempSync(join(tmpdir(), "pool-service-reconcile-receipts-agree-"));
  const registryPath = join(dir, "wallet-registry.json");
  writeFileSync(registryPath, JSON.stringify(REGISTRY));
  const sidecarPath = join(dir, "sidecar.beancount");
  writeFileSync(sidecarPath, [
    '2026-09-05 * "Tidepool cycle 2026-09-cycle-1 directed yield received"',
    "  Assets:Digital-Assets:EVM:Base:Pool:Barrier-Reserve  20 USDC",
    "  Assets:Digital-Assets:EVM:Base:Pool:Float  30 USDC",
    "  Assets:Digital-Assets:EVM:Base:Pool:Distributable-Pending  50 USDC",
    "  Income:Pool:Directed-Yield  -100 USDC",
    "",
  ].join("\n"));

  const fetchImpl = rpcFake({ balanceOf: 100_000_000n, decimals: 6, symbol: "USDC" }); // 100.0 USDC
  const result = await reconcilePoolReceipts({ walletRegistryPath: registryPath, walletId: "tidepool-pool-base", sidecarPath, journalRoot: dir, recordedAt: "2026-09-05T00:00:00Z" }, { fetchImpl });
  assert.equal(result.reconciled, true);
  assert.equal(result.agreed.length, 1);
  assert.equal(result.mismatch.length, 0);
  assert.match(result.receipt, /^ni:\/\/\//);
});

test("reconcilePoolReceipts: reports a mismatch, never silently corrects toward either side", async () => {
  const dir = mkdtempSync(join(tmpdir(), "pool-service-reconcile-receipts-mismatch-"));
  const registryPath = join(dir, "wallet-registry.json");
  writeFileSync(registryPath, JSON.stringify(REGISTRY));
  const sidecarPath = join(dir, "sidecar.beancount");
  writeFileSync(sidecarPath, [
    '2026-09-05 * "Tidepool cycle 2026-09-cycle-1 directed yield received"',
    "  Assets:Digital-Assets:EVM:Base:Pool:Barrier-Reserve  20 USDC",
    "  Assets:Digital-Assets:EVM:Base:Pool:Float  30 USDC",
    "  Assets:Digital-Assets:EVM:Base:Pool:Distributable-Pending  50 USDC",
    "  Income:Pool:Directed-Yield  -100 USDC",
    "",
  ].join("\n"));

  const fetchImpl = rpcFake({ balanceOf: 90_000_000n, decimals: 6, symbol: "USDC" }); // 90.0 USDC, does not agree
  const result = await reconcilePoolReceipts({ walletRegistryPath: registryPath, walletId: "tidepool-pool-base", sidecarPath, journalRoot: dir, recordedAt: "2026-09-05T00:00:00Z" }, { fetchImpl });
  assert.equal(result.reconciled, true);
  assert.equal(result.agreed.length, 0);
  assert.equal(result.mismatch.length, 1);
});

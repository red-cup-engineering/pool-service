import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { deriveSetOfPoolCycleTransactionsFromStore } from "../scripts/derive-set-of-pool-cycle-transactions.mjs";
import { readStore, writeStore } from "../src/store.mjs";
import { normalizeDirectedYieldReceipts } from "../src/directed-yield-receipts.mjs";

const RECEIPTS = [
  { memberAccount: "pool:account-org", amount: "100", commodity: "USDC", observedAt: "2026-09-01T00:00:00Z" },
];
const RECEIPT_EVIDENCE = normalizeDirectedYieldReceipts(RECEIPTS);

const SPLIT = Object.freeze({
  cycleId: "2026-09-cycle-1", commodity: "USDC", totalYield: "100", reserve: "20", float: "30", distributable: "50",
  fixedPortion: "25", votedPortion: "25",
  yieldEvidence: Object.freeze({
    recordNi: RECEIPT_EVIDENCE.evidenceNi,
    receiptCount: RECEIPT_EVIDENCE.receiptCount,
    observedThrough: RECEIPT_EVIDENCE.observedThrough,
  }),
  perEnterprise: [
    { enterpriseId: "ent-1", fixed: "12.5", voted: "12.5", total: "25" },
    { enterpriseId: "ent-2", fixed: "12.5", voted: "12.5", total: "25" },
  ],
});

test("derive-set-of-pool-cycle-transactions: books the sidecar headed like the house's other generated sidecars", () => {
  const dir = mkdtempSync(join(tmpdir(), "pool-service-cycle-tx-"));
  const statePath = join(dir, "pool.json");
  writeStore(statePath, { pool: { id: "t" }, tallies: [], draws: [], enterprises: [], votes: [], contests: [], cycleSplits: [SPLIT] });

  const sidecarPath = join(dir, "2026-09-01-pool-cycle-transactions.beancount");
  const result = deriveSetOfPoolCycleTransactionsFromStore(statePath, dir, {
    cycleId: "2026-09-cycle-1",
    directedYieldReceipts: RECEIPTS,
    receivedAt: "2026-09-01T00:00:00Z", distributedAt: "2026-09-05T00:00:00Z", recordedAt: "2026-09-05T00:00:00Z",
  }, { sidecarPath });

  assert.equal(result.booked, true);
  assert.equal(result.recovered, false);
  assert.equal(result.transactionCount, 4);
  assert.match(result.sidecarNi, /^ni:\/\/\/sha-256;/u);
  assert.match(result.receipt, /^ni:\/\/\//);
  const booking = readStore(statePath, null).cycleBookings[0];
  assert.equal(booking.cycleId, "2026-09-cycle-1");
  assert.equal(booking.sidecarNi, result.sidecarNi);
  assert.equal(booking.receipt, result.receipt);
  assert.equal(booking.recovered, false);

  const text = readFileSync(sidecarPath, "utf8");
  assert.match(text, /^; Generated by scripts\/derive-set-of-pool-cycle-transactions\.mjs \(@red-cup-engineering\/pool-service\)\. Do not hand-edit\./u);
  assert.match(text, /open Income:Pool:Directed-Yield/);
  assert.match(text, /Tidepool cycle 2026-09-cycle-1 directed yield received/);
});

test("derive-set-of-pool-cycle-transactions: --known-open accounts are not re-opened", () => {
  const dir = mkdtempSync(join(tmpdir(), "pool-service-cycle-tx-known-open-"));
  const statePath = join(dir, "pool.json");
  writeStore(statePath, { pool: { id: "t" }, tallies: [], draws: [], enterprises: [], votes: [], contests: [], cycleSplits: [SPLIT] });

  const knownOpenPath = join(dir, "known-open.beancount");
  writeFileSync(knownOpenPath, "2026-01-01 open Income:Pool:Directed-Yield\n2026-01-01 open Assets:Digital-Assets:EVM:Base:Pool:Barrier-Reserve\n");

  const sidecarPath = join(dir, "2026-09-01-pool-cycle-transactions.beancount");
  deriveSetOfPoolCycleTransactionsFromStore(statePath, dir, {
    cycleId: "2026-09-cycle-1",
    directedYieldReceipts: RECEIPTS,
    receivedAt: "2026-09-01T00:00:00Z", distributedAt: "2026-09-05T00:00:00Z", recordedAt: "2026-09-05T00:00:00Z",
  }, { sidecarPath, knownOpenPaths: [knownOpenPath] });

  const text = readFileSync(sidecarPath, "utf8");
  assert.equal(text.includes("open Income:Pool:Directed-Yield"), false);
  assert.equal(text.includes("open Assets:Digital-Assets:EVM:Base:Pool:Barrier-Reserve"), false);
  assert.match(text, /open Assets:Digital-Assets:EVM:Base:Pool:Float/);
});

test("derive-set-of-pool-cycle-transactions: throws when no cycle-split document exists for the cycle", () => {
  const dir = mkdtempSync(join(tmpdir(), "pool-service-cycle-tx-missing-"));
  const statePath = join(dir, "pool.json");
  writeStore(statePath, { pool: { id: "t" }, cycleSplits: [] });
  assert.throws(() => deriveSetOfPoolCycleTransactionsFromStore(statePath, dir, {
    cycleId: "nope", directedYieldReceipts: [], receivedAt: "2026-09-01T00:00:00Z", distributedAt: "2026-09-05T00:00:00Z", recordedAt: "2026-09-05T00:00:00Z",
  }), /no cycle-split document/);
});


test("derive-set-of-pool-cycle-transactions: repairs state after sidecar-only partial completion when expected directives match", () => {
  const dir = mkdtempSync(join(tmpdir(), "pool-service-cycle-tx-recovery-"));
  const statePath = join(dir, "pool.json");
  writeStore(statePath, { pool: { id: "t" }, cycleSplits: [SPLIT] });
  const sidecarPath = join(dir, "cycle.beancount");
  const request = {
    cycleId: "2026-09-cycle-1",
    directedYieldReceipts: [{ memberAccount: "pool:account-org", amount: "100", commodity: "USDC", observedAt: "2026-09-01T00:00:00Z" }],
    receivedAt: "2026-09-01T00:00:00Z",
    distributedAt: "2026-09-05T00:00:00Z",
    recordedAt: "2026-09-05T00:00:00Z",
  };

  const first = deriveSetOfPoolCycleTransactionsFromStore(statePath, dir, request, { sidecarPath });
  assert.equal(first.booked, true);
  const sidecarText = readFileSync(sidecarPath, "utf8");

  const state = readStore(statePath, null);
  delete state.cycleBookings;
  writeStore(statePath, state);

  const recovered = deriveSetOfPoolCycleTransactionsFromStore(statePath, dir, request, { sidecarPath });
  assert.equal(recovered.booked, true);
  assert.equal(recovered.recovered, true);
  assert.equal(recovered.sidecarNi, first.sidecarNi);
  assert.equal(readFileSync(sidecarPath, "utf8"), sidecarText);
  assert.equal(readStore(statePath, null).cycleBookings[0].recovered, true);
});

test("derive-set-of-pool-cycle-transactions: refuses sidecar recovery when a cycle marker exists but expected booking directives do not", () => {
  const dir = mkdtempSync(join(tmpdir(), "pool-service-cycle-tx-bad-recovery-"));
  const statePath = join(dir, "pool.json");
  writeStore(statePath, { pool: { id: "t" }, cycleSplits: [SPLIT] });
  const sidecarPath = join(dir, "cycle.beancount");
  writeFileSync(sidecarPath, '2026-09-01 * "fake"\n  cycle_id: "2026-09-cycle-1"\n', "utf8");
  const result = deriveSetOfPoolCycleTransactionsFromStore(statePath, dir, {
    cycleId: "2026-09-cycle-1",
    directedYieldReceipts: [{ memberAccount: "pool:account-org", amount: "100", commodity: "USDC", observedAt: "2026-09-01T00:00:00Z" }],
    receivedAt: "2026-09-01T00:00:00Z",
    distributedAt: "2026-09-05T00:00:00Z",
    recordedAt: "2026-09-05T00:00:00Z",
  }, { sidecarPath });
  assert.equal(result.booked, false);
  assert.match(result.reason, /expected transaction directive\(s\) are missing/u);
  assert.equal(readStore(statePath, null).cycleBookings, undefined);
});

test("derive-set-of-pool-cycle-transactions: the sidecar is a projection of the journal, and a pre-journal sidecar is admitted once", async () => {
  const { renderPoolCycleSidecar } = await import("../scripts/derive-set-of-pool-cycle-transactions.mjs");
  const dir = mkdtempSync(join(tmpdir(), "pool-service-cycle-tx-projection-"));
  const statePath = join(dir, "pool.json");
  const second = { ...SPLIT, cycleId: "2026-09-cycle-2" };
  writeStore(statePath, { pool: { id: "t" }, cycleSplits: [SPLIT, second] });
  const sidecarPath = join(dir, "2026-09-01-pool-cycle-transactions.beancount");
  const earlier = "; Generated by scripts/derive-set-of-pool-cycle-transactions.mjs (@red-cup-engineering/pool-service). Do not hand-edit.\n\n\n2026-08-01 open Equity:Pool:Opening\n";
  writeFileSync(sidecarPath, earlier);
  const request = (cycleId) => ({ cycleId, directedYieldReceipts: RECEIPTS, receivedAt: "2026-09-01T00:00:00Z", distributedAt: "2026-09-05T00:00:00Z", recordedAt: "2026-09-05T00:00:00Z" });

  assert.equal(deriveSetOfPoolCycleTransactionsFromStore(statePath, dir, request("2026-09-cycle-1"), { sidecarPath }).booked, true);
  const afterFirst = readFileSync(sidecarPath, "utf8");
  assert.ok(afterFirst.startsWith(earlier.trimEnd()));
  assert.match(afterFirst, /cycle_id: "2026-09-cycle-1"/u);

  writeFileSync(sidecarPath, "");
  assert.equal(renderPoolCycleSidecar(dir, sidecarPath), afterFirst);
  assert.equal(deriveSetOfPoolCycleTransactionsFromStore(statePath, dir, request("2026-09-cycle-2"), { sidecarPath }).booked, true);
  const text = readFileSync(sidecarPath, "utf8");
  assert.ok(text.startsWith(afterFirst.trimEnd()));
  assert.match(text, /cycle_id: "2026-09-cycle-2"/u);
  assert.equal((text.match(/open Equity:Pool:Opening/gu) ?? []).length, 1);
});
